// Writes supabase/seed.sql: the Games Sheet games (with their awards) and the
// player profiles from site-data.json, as inserts that skip rows Supabase
// already has. Run after changing the CSV or site-data.json:
//   node generate-supabase-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { gamesSheetState, readGamesSheet } from "./games-sheet.mjs";

const root = fileURLToPath(new URL(".", import.meta.url));
const sheet = gamesSheetState(readGamesSheet(join(root, "Blood on the Clocktower - Games Sheet.csv")));
const siteData = JSON.parse(readFileSync(join(root, "site-data.json"), "utf8"));

const text = value => `'${String(value ?? "").replaceAll("'", "''")}'`;
const json = value => `${text(JSON.stringify(value))}::jsonb`;

const profiles = new Map(siteData.players.map(player => [player.name, player]));
const roster = sheet.headers.slice(9);
siteData.players.forEach(player => { if (!roster.includes(player.name)) roster.push(player.name); });

const playerRows = roster.map((name, slot) => {
  const p = profiles.get(name) || {};
  return `  (${[
    text(name), slot, text(p.displayName || name), p.core ? "true" : "false", text(p.title), text(p.major), text(p.status),
    text(p.quote), text(p.photoPath), text(p.overallSkill), text(p.goodSkill), text(p.evilSkill), text(p.gameImpact),
    text(p.socialTrust), text(p.strengths), text(p.weaknesses),
  ].join(", ")})`;
});

const gameRows = sheet.games.map(game => {
  const awards = siteData.gameAwards?.[game.id] || {};
  return `  (${[
    text(game.id), text(game.source), text(game.date), text(game.outcome), text(game.finalDay), text(game.storyteller),
    game.playerCount, text(game.format), text(game.script), json(game.winNames), json(game.lossNames), json(game.roles),
    json(game.alignmentOverrides), json(awards.mangoNectar || []), json(awards.mushroomElixir || []),
  ].join(", ")})`;
});

const sql = `-- Generated by generate-supabase-seed.mjs. Do not edit by hand.
-- Loads the Games Sheet games and the player profiles into Supabase.
-- Run after supabase/setup.sql. Safe to re-run: rows that already exist
-- (including ones edited on the site) are left alone.

begin;

insert into public.players (
  name, slot, display_name, core, title, major, status, quote, photo_path,
  overall_skill, good_skill, evil_skill, game_impact, social_trust, strengths, weaknesses
) values
${playerRows.join(",\n")}
on conflict do nothing;

insert into public.games (
  id, source, date, outcome, final_day, storyteller, player_count, format, script,
  win_names, loss_names, roles, alignment_overrides, mango_nectar, mushroom_elixir
) values
${gameRows.join(",\n")}
on conflict do nothing;

commit;
`;

writeFileSync(join(root, "supabase", "seed.sql"), sql);
console.log(`Wrote supabase/seed.sql with ${playerRows.length} players and ${gameRows.length} games.`);
